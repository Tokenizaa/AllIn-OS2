import { z } from 'zod';

export const machineSchema = z.object({
  id: z.string().uuid(),
  nome: z.string().min(1),
  codigo: z.string().min(1),
  fabricante: z.string().optional(),
  modelo: z.string().optional(),
  numero_serie: z.string().optional(),
  data_aquisicao: z.string().or(z.date()).optional(),
  valor_aquisicao: z.number().optional(),
  localizacao_id: z.string().uuid().nullable().optional(),
  localizacao_detalhe: z.string().optional(),
  status: z.string().default('active'),
  capacidade_horaria: z.number().optional(),
  capacidade_operacional: z.number().optional(),
  disponibilidade: z.number().optional(),
  vida_util_anos: z.number().optional(),
  data_ultima_manutencao_preventiva: z.string().or(z.date()).nullable().optional(),
  data_proxima_manutencao_preventiva: z.string().or(z.date()).nullable().optional(),
  data_ultima_manutencao_corretiva: z.string().or(z.date()).nullable().optional(),
  manutencao_observacoes: z.string().nullable().optional(),
  especificacoes: z.any().optional(),
  observacoes: z.string().optional(),
  anexos: z.array(z.any()).optional(),
  created_at: z.string().datetime(),
  updated_at: z.string().datetime(),
  deleted_at: z.string().datetime().nullable().optional(),
});

export const createMachineSchema = z.object({
  nome: z.string().min(1),
  codigo: z.string().min(1),
  fabricante: z.string().optional(),
  modelo: z.string().optional(),
  numero_serie: z.string().optional(),
  data_aquisicao: z.string().or(z.date()).optional(),
  valor_aquisicao: z.number().optional(),
  localizacao_id: z.string().uuid().nullable().optional(),
  localizacao_detalhe: z.string().optional(),
  status: z.string().default('active'),
  capacidade_horaria: z.number().optional(),
  capacidade_operacional: z.number().optional(),
  disponibilidade: z.number().optional(),
  vida_util_anos: z.number().optional(),
  data_ultima_manutencao_preventiva: z.string().or(z.date()).nullable().optional(),
  data_proxima_manutencao_preventiva: z.string().or(z.date()).nullable().optional(),
  data_ultima_manutencao_corretiva: z.string().or(z.date()).nullable().optional(),
  manutencao_observacoes: z.string().nullable().optional(),
  especificacoes: z.any().optional(),
  observacoes: z.string().optional(),
  anexos: z.array(z.any()).optional(),
});

export const updateMachineSchema = z.object({
  nome: z.string().min(1).optional(),
  codigo: z.string().min(1).optional(),
  fabricante: z.string().optional(),
  modelo: z.string().optional(),
  numero_serie: z.string().optional(),
  data_aquisicao: z.string().or(z.date()).optional(),
  valor_aquisicao: z.number().optional(),
  localizacao_id: z.string().uuid().nullable().optional(),
  localizacao_detalhe: z.string().optional(),
  status: z.string().optional(),
  capacidade_horaria: z.number().optional(),
  capacidade_operacional: z.number().optional(),
  disponibilidade: z.number().optional(),
  vida_util_anos: z.number().optional(),
  data_ultima_manutencao_preventiva: z.string().or(z.date()).nullable().optional(),
  data_proxima_manutencao_preventiva: z.string().or(z.date()).nullable().optional(),
  data_ultima_manutencao_corretiva: z.string().or(z.date()).nullable().optional(),
  manutencao_observacoes: z.string().nullable().optional(),
  especificacoes: z.any().optional(),
  observacoes: z.string().optional(),
  anexos: z.array(z.any()).optional(),
});

export type Machine = z.infer<typeof machineSchema>;
export type CreateMachineDTO = z.infer<typeof createMachineSchema>;
export type UpdateMachineDTO = z.infer<typeof updateMachineSchema>;
export type MachineResponseDTO = Machine;
